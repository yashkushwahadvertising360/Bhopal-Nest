export function formatINR(amount: number): string {
  return '₹' + amount.toLocaleString('en-IN');
}

export function buildWhatsAppUrl(property: Property, customNote?: string): string {
  const phone = (property.ownerPhone || '919826011223').replace(/[^0-9]/g, '');
  const bhkText = property.bhk > 0 ? `${property.bhk} BHK ` : '';
  const text =
    customNote ||
    `Hi, I am interested in the ${bhkText}${property.type} "${property.title}" (ID: ${property.id}) in ${property.locality}, Bhopal listed at ${formatINR(property.rent)}/month on BhopalNest. Please share more details.`;
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}
